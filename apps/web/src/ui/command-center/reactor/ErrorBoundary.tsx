import { Component, type ReactNode } from 'react';

/** Contains a failure of the lazy chunk or of rendering, so the rest of the Command Center survives. */
export class ReactorErrorBoundary extends Component<
  { onError: () => void; children: ReactNode },
  { failed: boolean }
> {
  override state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  override componentDidCatch() {
    this.props.onError();
  }
  override render() {
    return this.state.failed ? null : this.props.children;
  }
}
